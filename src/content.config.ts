import { defineCollection, z } from 'astro:content';
import { glob } from 'astro/loaders';
import { AUTHOR } from './consts';

// Guides are long-form SEO content. The content agent will append `.mdx` files
// here daily; frontmatter must satisfy this schema or build fails (intentional —
// it's the quality gate that prevents a broken guide from shipping).
const guides = defineCollection({
  loader: glob({ pattern: '**/*.{md,mdx}', base: './src/content/guides' }),
  schema: ({ image }) =>
    z.object({
      title: z.string().min(10).max(80),
      description: z.string().min(50).max(180),
      pubDate: z.coerce.date(),
      updatedDate: z.coerce.date().optional(),
      category: z.enum(['ebook-readers', 'privacy', 'productivity']),
      tags: z.array(z.string()).default([]),
      heroImage: image().optional(),
      heroAlt: z.string().optional(),
      appCta: z.enum(['pagesage']).optional(),
      draft: z.boolean().default(false),
      // When generated by the content agent, this records the source keyword.
      // Manual guides can omit it.
      sourceKeyword: z.string().optional(),
      // Default to the house author — guides written by other contributors
      // can override via frontmatter. Keep aligned with AUTHOR in consts.ts.
      author: z.string().default(AUTHOR.name),
    }),
});

export const collections = { guides };
